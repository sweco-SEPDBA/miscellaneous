USE [master]
GO

IF NOT EXISTS (SELECT * FROM dbo.sysdatabases WHERE ('[' + name + ']' = '$(DATABASE_NAME)' OR name = '$(DATABASE_NAME)'))
BEGIN
    CREATE DATABASE [$(DATABASE_NAME)]
    COLLATE SQL_Latin1_General_CP1_CS_AS

    ALTER DATABASE [$(DATABASE_NAME)] SET COMPATIBILITY_LEVEL = 110 -- SQL Server 2012

    ALTER DATABASE [$(DATABASE_NAME)] SET ALLOW_SNAPSHOT_ISOLATION ON

    ALTER DATABASE [$(DATABASE_NAME)] SET READ_COMMITTED_SNAPSHOT ON

    ALTER DATABASE [$(DATABASE_NAME)] SET QUOTED_IDENTIFIER ON 

    ALTER DATABASE [$(DATABASE_NAME)] SET ANSI_NULLS ON 

    ALTER DATABASE [$(DATABASE_NAME)] SET ANSI_NULL_DEFAULT ON

    ALTER DATABASE [$(DATABASE_NAME)] SET ANSI_PADDING ON 

    ALTER DATABASE [$(DATABASE_NAME)] SET ANSI_WARNINGS ON

    ALTER DATABASE [$(DATABASE_NAME)] SET ARITHABORT ON

    ALTER DATABASE [$(DATABASE_NAME)] SET NUMERIC_ROUNDABORT OFF

    ALTER DATABASE [$(DATABASE_NAME)] SET CURSOR_CLOSE_ON_COMMIT ON 

    ALTER DATABASE [$(DATABASE_NAME)] SET CURSOR_DEFAULT  GLOBAL 

    ALTER DATABASE [$(DATABASE_NAME)] SET CONCAT_NULL_YIELDS_NULL ON 

    ALTER DATABASE [$(DATABASE_NAME)] SET RECURSIVE_TRIGGERS OFF 
END
GO

USE [$(DATABASE_NAME)]
GO

-- Create a role with permission to execute stored procedures.
-- This permission is required by the AD_SERVICE_ACCOUNT user.
IF NOT EXISTS (SELECT * FROM sys.database_principals WHERE name = N'db_executor' AND type = 'R')
BEGIN
    CREATE ROLE db_executor
    GRANT EXECUTE TO db_executor
END
GO

IF NOT EXISTS (SELECT * FROM dbo.syslogins WHERE name = N'$(AD_SERVICE_ACCOUNT)')
BEGIN
    CREATE LOGIN [$(AD_SERVICE_ACCOUNT)] FROM WINDOWS;
END
GO

IF NOT EXISTS (SELECT * FROM [sys].[database_principals] WHERE lower([name]) = lower(N'$(AD_SERVICE_ACCOUNT)'))
BEGIN
    CREATE USER [$(AD_SERVICE_ACCOUNT)] FOR LOGIN [$(AD_SERVICE_ACCOUNT)];
    EXEC sp_addrolemember 'db_executor', '$(AD_SERVICE_ACCOUNT)'
    EXEC sp_addrolemember 'db_ddladmin', '$(AD_SERVICE_ACCOUNT)'
    EXEC sp_addrolemember 'db_datareader', '$(AD_SERVICE_ACCOUNT)'
    EXEC sp_addrolemember 'db_datawriter', '$(AD_SERVICE_ACCOUNT)'
END
GO