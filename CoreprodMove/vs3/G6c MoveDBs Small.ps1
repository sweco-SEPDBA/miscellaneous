Restore-DbaDatabase -SqlInstance SESTODS073.sweco.se\SWSQL06PC -MaintenanceSolutionBackup -IgnoreLogBackup -NoRecovery -SqlCredential $credSecondary 

$endTime = Get-Date
$elapsedTime = $endTime - $startTime
